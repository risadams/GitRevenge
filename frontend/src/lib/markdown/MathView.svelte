<script lang="ts">
  // TeX rendered by KaTeX as MathML, which the webview draws natively: no KaTeX stylesheet
  // or fonts. trust: false keeps \href, \url and HTML extensions out, so the markup is only
  // what KaTeX generates; a parse error shows the source with the error, not a crash.
  import katex from 'katex'

  let { tex, display = false }: { tex: string; display?: boolean } = $props()

  let html = $derived(
    katex.renderToString(tex, { displayMode: display, output: 'mathml', throwOnError: false, trust: false, strict: 'ignore' }),
  )
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- MathML generated by KaTeX with trust off -->
{#if display}<div class="math display">{@html html}</div>{:else}<span class="math">{@html html}</span>{/if}

<style>
  .display {
    margin: 10px 0;
    overflow-x: auto;
    text-align: center;
  }

  .math :global(math) {
    font-size: 1.1em;
  }

  /* KaTeX marks source it couldn't parse in its error colour; use ours. */
  .math :global([style*='color']) {
    color: var(--danger) !important;
  }
</style>
